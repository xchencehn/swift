'use strict';
const fs = require('node:fs'),
  path = require('node:path'),
  crypto = require('node:crypto');
const root = path.resolve(__dirname, '../..'),
  output = path.join(root, 'public/vendor/code-editor');
const result = require('esbuild').buildSync({
  absWorkingDir: root,
  entryPoints: ['scripts/build/code-editor-entry.mjs'],
  outdir: output,
  entryNames: 'editor-[hash]',
  chunkNames: 'chunks/[name]-[hash]',
  bundle: true,
  splitting: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  minify: true,
  charset: 'utf8',
  legalComments: 'none',
  metafile: true,
  write: false,
  logLevel: 'silent',
});
const generated = new Map(
  result.outputFiles.map((file) => [file.path, Buffer.from(file.contents)]),
);
const packages = new Map();
for (const input of Object.keys(result.metafile.inputs).filter((name) =>
  name.startsWith('node_modules/'),
)) {
  let directory = path.dirname(path.join(root, input));
  while (directory.startsWith(path.join(root, 'node_modules'))) {
    const manifest = path.join(directory, 'package.json');
    if (fs.existsSync(manifest)) {
      const data = JSON.parse(fs.readFileSync(manifest, 'utf8'));
      if (data.name && !packages.has(data.name)) {
        const license = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'license', 'license.md']
          .map((name) => path.join(directory, name))
          .find((name) => fs.existsSync(name));
        if (!license) throw new Error(`Missing license for ${data.name}`);
        packages.set(data.name, {
          name: data.name,
          version: data.version,
          license: fs.readFileSync(license, 'utf8'),
        });
      }
      break;
    }
    directory = path.dirname(directory);
  }
}
const ordered = [...packages.values()].sort((a, b) => a.name.localeCompare(b.name));
generated.set(
  path.join(output, 'LICENSES.txt'),
  Buffer.from(
    ordered.map((item) => `${item.name} ${item.version}\n${item.license.trim()}\n`).join('\n'),
  ),
);
const entry = Object.entries(result.metafile.outputs).find(
  ([, value]) => value.entryPoint === 'scripts/build/code-editor-entry.mjs',
)[0];
const asset = path
  .relative(path.join(root, 'public'), path.resolve(root, entry))
  .replaceAll(path.sep, '/');
generated.set(
  path.join(root, 'public/files/code-editor-assets.js'),
  Buffer.from(
    `/* Generated by scripts/build/build-code-editor.js. */\nglobalThis.StudioCodeEditorAsset = ${JSON.stringify(asset)};\n`,
  ),
);
generated.set(
  path.join(output, 'README.md'),
  Buffer.from(
    '# CodeMirror 6\n\nGenerated from scripts/build/code-editor-entry.mjs with the exact versions in package-lock.json. Run `node scripts/build/build-code-editor.js` to rebuild, or add `--check` to verify. The editor and language modules load only when a file source view is opened.\n\nUpstream: https://codemirror.net/ . Licenses for every bundled dependency are in LICENSES.txt.\n',
  ),
);
const check = process.argv.includes('--check');
if (!check) fs.rmSync(output, { recursive: true, force: true });
for (const [file, bytes] of generated) {
  if (check) {
    if (!fs.existsSync(file) || !fs.readFileSync(file).equals(bytes))
      throw new Error(
        `Code editor asset differs: ${path.relative(root, file)}. Run node scripts/build/build-code-editor.js.`,
      );
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, bytes);
  }
}
const hash = crypto.createHash('sha256');
for (const [file, bytes] of [...generated].sort())
  hash.update(path.relative(root, file)).update(bytes);
console.log(
  `CodeMirror assets ${check ? 'verified' : 'generated'}: ${result.outputFiles.length} modules, ${ordered.length} licenses, SHA256 ${hash.digest('hex')}.`,
);
